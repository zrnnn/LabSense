"""Embed LabSense's offline setup pages in their matching firmware variants."""
from pathlib import Path
import argparse,gzip,hashlib,json,re
ROOT=Path(__file__).resolve().parents[1]
VARIANTS={'release':('web/setup-release','firmware/release')}
def main():
 parser=argparse.ArgumentParser();parser.add_argument('--variant',choices=VARIANTS);parser.add_argument('--check',action='store_true');args=parser.parse_args()
 for variant in ([args.variant] if args.variant else VARIANTS):
  web,firmware=VARIANTS[variant];html=(ROOT/web/'index.html').read_bytes();compressed=gzip.compress(html,compresslevel=9,mtime=0)
  rows=[','.join('0x%02x'%b for b in compressed[i:i+20]) for i in range(0,len(compressed),20)]
  header='#pragma once\n// Generated by tools/build_portal_assets.py. No external assets.\n#include "esphome/core/hal.h"\nnamespace esphome::captive_portal {\nconstexpr uint8_t INDEX_GZ[] PROGMEM = {\n'+',\n'.join(rows)+'\n};\n}\n'
  output=ROOT/firmware/'components/captive_portal/captive_index.h'
  if args.check:
   # gzip headers/deflate bytes can differ across Python and zlib versions.
   # Compare the actual embedded content instead of compressor output.
   encoded=bytes(int(value,16) for value in re.findall(r'0x[0-9a-f]{2}',output.read_text()))
   assert gzip.decompress(encoded)==html, f'{variant}: regenerate portal assets'
   manifest=json.loads((ROOT/web/'asset_manifest.json').read_text())
   assert manifest['sha256']==hashlib.sha256(html).hexdigest(),variant
  else:
   output.write_text(header)
   (ROOT/web/'asset_manifest.json').write_text(json.dumps({'source':web+'/index.html','source_bytes':len(html),'gzip_bytes':len(compressed),'sha256':hashlib.sha256(html).hexdigest(),'upstream':'ESPHome 2026.9.1','variant':variant,'external_requests':False},indent=2)+'\n')
  print(variant+': embedded page '+('matches' if args.check else 'updated'))
if __name__=='__main__':main()
